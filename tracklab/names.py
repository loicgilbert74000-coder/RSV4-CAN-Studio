def fr(name):
    """Nom affiché d'un signal, en français."""
    if name in NOMS_FR:
        return NOMS_FR[name]
    m = re.match("^(?:SRC_)?([0-9A-Fa-f]{2,3})([BWN])(\\d+)$", name)
    if m:
        return "Inconnu · " + {"B": "octet", "W": "mot", "N": "quartet"}[m.group(2)] + " " + m.group(3)
    return name.replace("_", " ")
